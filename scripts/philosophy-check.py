    for violation in violations:
        if violation not in seen:
            seen.add(violation)
            unique_violations.append(violation)
    violations = unique_violations

    if violations:
        print("philosophy-check failed:")
        for violation in violations:
            print(f" - {violation}")
        return 1

    print("philosophy-check passed")
    return 0


