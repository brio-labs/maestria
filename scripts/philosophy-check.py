def production_strip_line_comments(body: str) -> str:
    """Remove single-line `//` comments (but not `//!` doc-comments)."""
    lines = []
    for line in body.splitlines(keepends=True):
        stripped = line.lstrip()
        if (
            stripped.startswith("// ")
            or stripped.startswith("//\n")
            or stripped.startswith("//\r")
        ):
            lines.append("\n")
        elif stripped.startswith("/*"):
            lines.append("\n")
        else:
            lines.append(line)
    return "".join(lines)


def _workspace_member_roots() -> list[Path] | None:
    """Discover workspace packages from Cargo members, globs, excludes, and root."""
    manifest_path = ROOT / "Cargo.toml"
    content = read_text(manifest_path)
    if content is None:
        return None
    document = _toml_document(content)
    workspace = document.get("workspace")
    package = document.get("package")
    if not isinstance(workspace, dict) and not isinstance(package, dict):
        return None

    roots: set[Path] = set()
    if isinstance(package, dict):
        roots.add(ROOT)
    members = workspace.get("members", []) if isinstance(workspace, dict) else []
    if isinstance(members, str):
        members = [members]
    if isinstance(members, list):
        for member in members:
            if not isinstance(member, str):
                continue
            matches = list(ROOT.glob(member))
            if not matches and (ROOT / member).is_dir():
                matches = [ROOT / member]
            for match in matches:
                candidate = match.parent if match.name == "Cargo.toml" else match
                if candidate.is_dir() and (candidate / "Cargo.toml").is_file():
                    roots.add(candidate)

    excluded: set[Path] = set()
    excludes = workspace.get("exclude", []) if isinstance(workspace, dict) else []
    if isinstance(excludes, str):
        excludes = [excludes]
    if isinstance(excludes, list):
        for excluded_pattern in excludes:
            if not isinstance(excluded_pattern, str):
                continue
            matches = list(ROOT.glob(excluded_pattern))
            if not matches and (ROOT / excluded_pattern).exists():
                matches = [ROOT / excluded_pattern]
            for match in matches:
                excluded.add(match.parent if match.name == "Cargo.toml" else match)
    return sorted(
        root
        for root in roots
        if not any(root == excluded_root or excluded_root in root.parents for excluded_root in excluded)
    )


def _path_dependency_roots(crate_root: Path) -> set[Path]:
    """Find in-tree packages referenced by direct or inherited path dependencies."""
    document = _toml_document(read_text(crate_root / "Cargo.toml") or "")
    workspace_specs = _workspace_dependency_specifications(
        read_text(ROOT / "Cargo.toml")
    )
    roots: set[Path] = set()

    def collect(table: object) -> None:
        if not isinstance(table, dict):
            return
        for dependency, specification in table.items():
            if not isinstance(specification, dict):
                continue
            resolved = specification
            base = crate_root
            if specification.get("workspace") is True:
                resolved = workspace_specs.get(
                    _normalize_dependency_name(str(dependency)), {}
                )
                base = ROOT
            dependency_path = resolved.get("path")
            if not isinstance(dependency_path, str):
                continue
            candidate = (base / dependency_path).resolve()
            try:
                candidate.relative_to(ROOT.resolve())
            except ValueError:
                continue
            if (candidate / "Cargo.toml").is_file():
                roots.add(candidate)

    for table_name in ("dependencies", "dev-dependencies", "build-dependencies"):
        collect(document.get(table_name))
    targets = document.get("target", {})
    if isinstance(targets, dict):
        for target in targets.values():
            if not isinstance(target, dict):
                continue
            for table_name in ("dependencies", "dev-dependencies", "build-dependencies"):
                collect(target.get(table_name))
    return roots


def _workspace_production_roots() -> list[Path] | None:
    roots = _workspace_member_roots()
    if roots is None:
        return None
    discovered = set(roots)
    pending = list(roots)
    while pending:
        crate_root = pending.pop()
        for dependency_root in _path_dependency_roots(crate_root):
            if dependency_root not in discovered:
                discovered.add(dependency_root)
                pending.append(dependency_root)
    return sorted(discovered)


def _library_target_path(crate_root: Path) -> Path | None:
    manifest = _toml_document(read_text(crate_root / "Cargo.toml") or "")
    lib = manifest.get("lib")
    if isinstance(lib, dict) and isinstance(lib.get("path"), str):
        return crate_root / str(lib["path"])
    default = crate_root / "src" / "lib.rs"
    return default if default.is_file() else None


def production_lib_paths() -> list[Path]:
    roots = _workspace_production_roots()
    if roots is None:
        candidates = ROOT.glob("**/src/lib.rs")
    else:
        candidates = (_library_target_path(root) for root in roots)
    return sorted(
        source
        for source in candidates
        if source is not None
        and source.is_file()
        and not should_skip(source)
        and not is_test_source(source)
    )


def _rust_item_fragments(text: str) -> list[str]:
    """Split top-level Rust items without relying on keyword-shaped regexes."""
    source = _rust_syntax(text)
    fragments: list[str] = []
    index = 0
    while index < len(source):
        while index < len(source) and source[index].isspace():
            index += 1
        if index >= len(source):
            break
        if source.startswith("#[", index) or source.startswith("#![", index):
            opening = source.find("[", index)
            # Attributes may contain nested macro delimiters, so balance square
            # brackets directly instead of treating the attribute as an item.
            depth = 0
            cursor = opening
            while cursor != -1 and cursor < len(source):
                if source[cursor] == "[":
                    depth += 1
                elif source[cursor] == "]":
                    depth -= 1
                    if depth == 0:
                        cursor += 1
                        break
                cursor += 1
            if opening == -1 or depth:
                break
            index = cursor
            continue

        start = index
        stack: list[str] = []
        close_for = {")": "(", "]": "[", "}": "{"}
        ended = False
        while index < len(source):
            token = source[index]
            if token in "([{":
                if token == "{" and not stack:
                    prefix = source[start:index]
                    if re.match(r"\s*(?:pub(?:\s*\([^)]*\))?\s+)?use\b", prefix):
                        stack.append(token)
                    else:
                        closing = _matching_delimiter(source, index, "{", "}")
                        if closing is None:
                            index = len(source)
                        else:
                            index = closing + 1
                        fragments.append(source[start:index])
                        ended = True
                        break
                else:
                    stack.append(token)
            elif token in close_for and stack:
                if stack[-1] == close_for[token]:
                    stack.pop()
            elif token == ";" and not stack:
                index += 1
                fragments.append(source[start:index])
                ended = True
                break
            index += 1
        if not ended:
            if start < len(source):
                fragments.append(source[start:index])
            break
    return fragments


def _facade_item_allowed(fragment: str) -> bool:
    item = fragment.strip()
    if not item:
        return True
    # Visibility is deliberately required for reexports: ordinary implementation
    # imports belong in the implementation module, not in the façade.
    use_match = re.match(r"^(pub(?:\s*\([^)]*\))?)\s+use\b", item, re.DOTALL)
    if use_match is not None:
        use_source = _rust_syntax(item)
        return "*" not in use_source
    mod_match = re.match(
        r"^(?:(?:pub(?:\s*\([^)]*\))?|unsafe)\s+)*mod\s+[A-Za-z_][A-Za-z0-9_]*\s*;\s*$",
        item,
        re.DOTALL,
    )
    return mod_match is not None


def scan_facade_boundaries() -> list[str]:
    """Require every production library target to be a declarative façade."""
    violations = []
    for source in production_lib_paths():
        rel_path = source.relative_to(ROOT).as_posix()
        content = read_text(source)
        if content is None:
            continue
        invalid_items = [
            fragment for fragment in _rust_item_fragments(content)
            if not _facade_item_allowed(fragment)
        ]
        if invalid_items:
            violations.append(
                f"{rel_path} contains {len(invalid_items)} implementation item(s); "
                f"implementation body/item detected (lib.rs should be a façade per Rule 19)"
            )
    return violations


def scan_cohesion() -> list[str]:
    """Emit cohesion / concept-density signals for large façade modules.

    Flags lib.rs files where the ratio of logical lines per declared module
    exceeds a heuristic threshold, indicating a single file may be carrying
    too many responsibilities.
    """
    violations = []
    for rel_path, declared_modules in RESPONSIBILITY_MAPS.items():
        source = ROOT / rel_path
        if rel_path in ADR_MODULE_EXEMPTIONS:
            continue
        if not source.exists():
            continue
        content = read_text(source)
        if content is None:
            continue
        production = content.split("#[cfg(test)]", 1)[0]
        logical = logical_line_count(production)
        num_modules = len(declared_modules)
        if num_modules == 0:
            continue
        density = logical / num_modules
        # If there are more than 15 logical lines per declared module in the
        # lib.rs, the façade is likely accumulating responsibility that
        # belongs in sibling modules.
        if density > 15.0:
            violations.append(
                f"{rel_path} has {density:.1f} logical lines per module "
                f"({logical} lines across {num_modules} modules) — "
                f"cohesion signal: extract implementation to modules"
            )
    return violations


_FN_DECL_PATTERN = re.compile(
    r"^\s*(?:pub(?:\s*\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)\s*\(",
    re.MULTILINE,
)


def _find_function_bodies(text: str) -> list[tuple[str, str]]:
    """Extract (name, body) for each top-level function in *text*."""
    results: list[tuple[str, str]] = []
    i = 0
    while i < len(text):
        match = _FN_DECL_PATTERN.search(text, i)
        if match is None:
            break
        name = match.group(1)
        j = match.end()
        brace_depth = 0
        in_string = False
        string_char = None
        start = 0
        while j < len(text):
            c = text[j]
            if in_string:
                if c == "\\" and j + 1 < len(text):
                    j += 2
                    continue
                if c == string_char:
                    in_string = False
                j += 1
                continue
            if c in "\"'":
                in_string = True
                string_char = c
                j += 1
                continue
            if c == "{":
                if brace_depth == 0:
                    start = j
                brace_depth += 1
            elif c == "}":
                brace_depth -= 1
                if brace_depth == 0:
                    body = text[start + 1 : j]
                    results.append((name, body))
                    i = j + 1
                    break
            j += 1
        else:
            break
    return results


def scan_function_sizes() -> list[str]:
    """Flag production functions that exceed the logical-line budget."""
    violations: list[str] = []
    for source in ROOT.rglob("*.rs"):
        if should_skip(source):
            continue
        if is_test_source(source):
            continue
        rel_path = source.relative_to(ROOT)
        rel = rel_path.as_posix()
        content = read_text(source)
        if content is None:
            continue
        exemptions = FUNCTION_SIZE_EXEMPTIONS.get(rel, {})
        scrubbed = _scrubbed_production(source)
        for name, body in _find_function_bodies(scrubbed):
            lines = _logical_line_count_scrubbed(body)
            if lines > MAX_FUNCTION_LOGICAL_LINES and name not in exemptions:
                violations.append(
                    f"{rel} function `{name}` has {lines} logical lines "
                    f"(limit {MAX_FUNCTION_LOGICAL_LINES})"
                )
    return violations


def _statement_terminator_count(line: str) -> int:
    """Count statement terminators outside grouping delimiters."""
    round_depth = 0
    square_depth = 0
    count = 0
    for token in line:
        if token == "(":
            round_depth += 1
        elif token == ")" and round_depth:
            round_depth -= 1
        elif token == "[":
            square_depth += 1
        elif token == "]" and square_depth:
            square_depth -= 1
        elif token == ";" and round_depth == 0 and square_depth == 0:
            count += 1
    return count


def scan_readability_style() -> list[str]:
    one_line_function = re.compile(r"(?m)\bfn\s+\w+\b[^{\n]*\{([^{}\n]*)\}")
    violations: list[str] = []
    for source in ROOT.rglob("*.rs"):
        if should_skip(source) or is_test_source(source):
            continue
        content = read_text(source)
        if content is None:
            continue
        production = production_rust(content)
        scrubbed = _rust_syntax(production)
        code_only = _rust_syntax(production, "\0")
        rel = source.relative_to(ROOT).as_posix()
        for line_number, line in enumerate(code_only.splitlines(), 1):
            code_line = line.replace("\0", "")
            if code_line.strip() and len(code_line.rstrip()) > MAX_PRODUCTION_LINE_WIDTH:
                violations.append(
                    f"{rel}:{line_number} production code line is "
                    f"{len(code_line.rstrip())} characters "
                    f"(limit {MAX_PRODUCTION_LINE_WIDTH})"
                )
        for line_number, line in enumerate(scrubbed.splitlines(), 1):
            if line.strip() and _statement_terminator_count(line) > 1:
                violations.append(
                    f"{rel}:{line_number} has multiple production statements on one line"
                )
        for match in one_line_function.finditer(scrubbed):
            body = match.group(1).strip()
            if not body:
                continue
            line_number = scrubbed.count("\n", 0, match.start()) + 1
            violations.append(
                f"{rel}:{line_number} has a one-line production function body; "
                "expand it into a readable block"
            )
    return violations


def scan_mixed_responsibilities() -> list[str]:
    """Flag non-façade modules that declare many sub-modules and are large.

    Heuristic: a regular .rs file (not lib.rs / mod.rs / main.rs) that
    declares 3+ child modules *and* exceeds 300 logical lines is likely
    accumulating mixed responsibilities.
    """
    violations: list[str] = []
    mod_pattern = re.compile(
        r"^\s*(?:pub(?:\s*\([^)]*\))?\s+)?mod\s+([a-z0-9_]+)\s*;",
        re.MULTILINE,
    )
    for source in ROOT.rglob("*.rs"):
        if should_skip(source):
            continue
        if is_test_source(source):
            continue
        if source.name in {"lib.rs", "mod.rs", "main.rs"}:
            continue
        rel_path = source.relative_to(ROOT)
        rel = rel_path.as_posix()
        if rel in MIXED_RESPONSIBILITY_EXEMPTIONS:
            continue
        content = read_text(source)
        if content is None:
            continue
        production = production_rust(content)
        mods = mod_pattern.findall(production)
        logical = _logical_line_count_scrubbed(_scrubbed_production(source))
        if len(mods) >= 3 and logical > 300:
            violations.append(
                f"{rel} has {len(mods)} child modules and {logical} logical lines — "
                f"mixed-responsibility signal: extract to dedicated module or ADR"
            )
    return violations


