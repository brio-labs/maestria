def scan_generated_blobs() -> list[str]:
    """Rule 38: no generated blobs under production source paths.

    A production Rust file carrying a code-generation marker is either
    vendored output (which must move out of the tree) or hand-edited
    generated code (which must become a real source file). Test fixtures
    are exempt: generated test data is legitimate.
    """
    violations = []
    for source in _production_rust_files(skip_tests=True):
        content = read_text(source)
        if content is None:
            continue
        production = production_rust(content)
        for marker in GENERATED_BLOB_MARKERS:
            if marker in production:
                violations.append(
                    f"{source.relative_to(shared.ROOT)} contains generated-code marker {marker!r}"
                )
                break
    return violations


def scan_string_typed_errors() -> list[str]:
    """Rule 24: failure information is preserved; a `TryFrom`/`FromStr`
    implementation whose error type is a bare `String` discards the typed
    validation variants at the conversion boundary."""
    violations = []
    for source in _production_rust_files(skip_tests=True):
        content = read_text(source)
        if content is None:
            continue
        production = production_rust(content)
        for match in FORBIDDEN_STRING_ERROR_PATTERN.finditer(production):
            line_number = content.count("\n", 0, match.start()) + 1
            violations.append(
            f"{source.relative_to(shared.ROOT)}:{line_number} uses String as a "
            "conversion error type; use a typed error"
        )
    return violations


