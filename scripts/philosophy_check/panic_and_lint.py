def scan_debug_output() -> list[str]:
    """Ban debugging leftovers and library console writes.

    `dbg!` is a debugging leftover anywhere, including tests. The
    `print!`/`println!`/`eprint!`/`eprintln!` family is only legitimate in
    app crates that own a console; library crates must emit through
    `tracing` so output is structured, filtered, and testable.
    """
    violations = []
    for source in _production_rust_files(skip_tests=False):
        content = read_text(source)
        if content is None:
            continue
        is_app = any(segment in APP_CRATE_DIRS for segment in source.parts)
        for pattern, description in DEBUG_OUTPUT_PATTERNS:
            if description.startswith("a dbg!"):
                continue  # dbg! is banned everywhere; handled below.
            if is_app:
                continue  # App crates own their console output.
            if re.search(pattern, content):
                violations.append(
                    f"{source.relative_to(shared.ROOT)} contains {description}"
                )
        if re.search(r"\bdbg!\s*\(", content):
            violations.append(
                f"{source.relative_to(shared.ROOT)} contains a dbg! debug-print call"
            )
    return violations


def scan_kernel_interior_mutability() -> list[str]:
    """Rule 1/21: kernel domain and governance code has no shared ownership
    or interior mutability.

    `Rc`/`RefCell`/`Cell`/`Mutex`/`RwLock`/`OnceLock`/`OnceCell`/`LazyLock`
    and `thread_local!` introduce hidden global state or uncontrolled
    concurrency into deterministic code. The in-memory port adapters under
    `maestria-ports/src/in_memory` are test doubles with an adapter role and
    are exempt; domain and governance are not.
    """
    violations = []
    for kernel_root in shared.KERNEL_ROOTS:
        for source in (kernel_root / "src").rglob("*.rs"):
            if kernel_root.name == "maestria-ports" and "in_memory" in source.parts:
                continue
            content = read_text(source)
            if content is None:
                continue
            rel = source.relative_to(shared.ROOT)
            for pattern in KERNEL_INTERIOR_MUTABILITY_PATTERNS:
                if re.search(pattern, content):
                    violations.append(
                        f"{rel} contains interior-mutability or shared-ownership "
                        f"token {pattern!r}"
                    )
    return violations


def scan_production_asserts() -> list[str]:
    """Rule 11 defense-in-depth: shipped code must not assert.

    `assert!`/`assert_eq!`/`assert_ne!`/`assert_matches!` panic on failure
    exactly like `panic!`, so production code must return typed errors.
    clippy::panic already gates this in CI; the checker keeps the class
    banned even when clippy flags are relaxed. Test sources and inline
    `#[cfg(test)]` items are exempt.
    """
    violations = []
    for source in _production_rust_files(skip_tests=True):
        content = read_text(source)
        if content is None:
            continue
        production = _scrubbed_production(source)
        for match in _PRODUCTION_ASSERT_PATTERN.finditer(production):
            line_number = content.count("\n", 0, match.start()) + 1
            violations.append(
                f"{source.relative_to(shared.ROOT)}:{line_number} contains a production "
                "assert; use a typed error"
            )
    return violations


def _doc_block_above(text: str, position: int) -> str:
    """Contiguous doc-comment (`///`) lines immediately above *position*,
    skipping blank lines and single-line attributes."""
    lines = text[:position].splitlines()
    docs: list[str] = []
    for line in reversed(lines):
        stripped = line.strip()
        if stripped.startswith("///"):
            docs.append(stripped)
        elif not stripped or stripped.startswith("#[") or stripped.startswith("//!"):
            continue
        else:
            break
    return "\n".join(reversed(docs))


def scan_cancellation_docs() -> list[str]:
    """Rule 34: public async operations document cancellation behavior.

    A `pub async fn` without a doc comment mentioning cancellation leaves
    callers unable to reason about drop/stale-result semantics.
    """
    violations = []
    for source in _production_rust_files(skip_tests=True):
        content = read_text(source)
        if content is None:
            continue
        production = production_rust(content)
        for match in _PUBLIC_ASYNC_FN_PATTERN.finditer(production):
            docs = _doc_block_above(production, match.start())
            if not re.search(r"\bcancel", docs, re.IGNORECASE):
                violations.append(
                    f"{source.relative_to(shared.ROOT)} `{match.group(1)}` is a public async "
                    "operation without a # Cancellation doc section"
                )
    return violations


def scan_bypassable_validation() -> list[str]:
    """Rule 56: validated kernel values must not expose bypassable constructors.

    A kernel struct that (a) carries a validating serde `try_from` conversion
    or a fallible constructor, and (b) still exposes public fields, lets
    callers build values that skip the validation. The validated model is
    private fields plus a fallible boundary constructor (the SearchPlan /
    ContentHash pattern).
    """
    violations = []
    for source in _kernel_rust_files(skip_tests=True):
        content = read_text(source)
        if content is None:
            continue
        production = _scrubbed_production(source)
        if not production:
            continue
        rel = source.relative_to(shared.ROOT)

        for struct_name, fields in _named_struct_fields_with_visibility(production):
            public_fields = [name for name, _, is_pub in fields if is_pub]
            if not public_fields:
                continue
            validated = False
            # (a) a serde try_from attribute whose next item is this struct
            for attr in _SERDE_TRY_FROM_PATTERN.finditer(production):
                between = production[attr.end() :]
                next_item = re.search(
                    r"^\s*(?:pub(?:\s*\([^)]*\))?\s+)?"
                    r"(?:struct|enum|impl|fn|mod|type|const)\s+",
                    between,
                    re.MULTILINE,
                )
                if (
                    next_item is not None
                    and between[next_item.start() :].lstrip().startswith(
                        f"struct {struct_name}"
                    )
                ):
                    validated = True
                    break
            if not validated:
                # (b) a fallible constructor inside `impl <struct_name>`
                for candidate in _FALLIBLE_CONSTRUCTOR_PATTERN.finditer(production):
                    if _function_belongs_to_struct(
                        production, candidate.start(), struct_name
                    ):
                        validated = True
                        break
            if not validated:
                # (c) a `TryFrom<...> for <struct_name>` conversion
                for impl_match in _TRY_FROM_IMPL_PATTERN.finditer(production):
                    if impl_match.group(1) == struct_name:
                        validated = True
                        break
            if validated:
                violations.append(
                    f"{rel} struct `{struct_name}` exposes public fields "
                    f"({', '.join(public_fields)}) alongside a validating "
                    "conversion; make fields private and construct through a "
                    "fallible boundary constructor"
                )
    return violations


def _function_belongs_to_struct(text: str, fn_start: int, struct_name: str) -> bool:
    """True when the fallible constructor at *fn_start* sits inside an
    `impl <struct_name> { ... }` block."""
    impl_matches = list(re.finditer(r"impl\s+(?:<[^>]*>\s+)?(\w+)\s*\{", text))
    for impl_match in reversed(impl_matches):
        opening = text.find("{", impl_match.start())
        closing = _matching_delimiter(text, opening, "{", "}")
        if closing is None:
            continue
        if opening < fn_start < closing:
            return impl_match.group(1) == struct_name
    return False
